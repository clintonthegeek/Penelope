#!/bin/bash
# Generate Arch PKGBUILDs for a Penelope release.
#
# Usage: packaging/generate-pkgbuild.sh [version] [output-dir]
#
# The version defaults to project(Penelope VERSION ...) in CMakeLists.txt,
# the same definition the About dialog, --version and CPack use. Two
# packages are written:
#
#   penelope/       tagged release, source pinned to v<version>
#   penelope-git/   VCS package, tracks the default branch
#
# When makepkg is available the matching .SRCINFO is generated too; that is
# what AUR wants. The release workflow attaches both PKGBUILDs to the GitHub
# release, and makepkg can be run directly on either directory.

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
version="${1:-}"
out="${2:-$root/packaging/out}"

if [[ -z "$version" ]]; then
    version="$(sed -n 's/^project(Penelope VERSION \([0-9][0-9.]*\).*/\1/p' "$root/CMakeLists.txt")"
fi
if [[ ! "$version" =~ ^[0-9]+(\.[0-9]+)+$ ]]; then
    echo "generate-pkgbuild: invalid version '$version'" >&2
    echo "usage: $0 [version] [output-dir]" >&2
    exit 1
fi

repo_url="https://github.com/clintonthegeek/Penelope.git"
pkgdesc="A beautiful paginated markdown reader"
url="https://github.com/clintonthegeek/Penelope"

deps="    'qt6-base'
    'kcoreaddons'
    'ki18n'
    'kxmlgui'
    'kwidgetsaddons'
    'kiconthemes'
    'kconfig'
    'kconfigwidgets'
    'kio'
    'syntax-highlighting'
    'kdbusaddons'
    'poppler-qt6'
    'md4c'
    'hyphen'
    'harfbuzz'
    'harfbuzz-icu'
    'freetype2'
    'fontconfig'
    'icu'
    'zlib'"

makedeps="    'cmake'
    'ninja'
    'extra-cmake-modules'
    'git'"

build_and_package() {
    local srcdir="$1"
    cat <<EOF

build() {
    cmake -S "\$srcdir/$srcdir" -B build -G Ninja \\
        -DCMAKE_BUILD_TYPE=Release \\
        -DCMAKE_INSTALL_PREFIX=/usr \\
        -DBUILD_TESTING=OFF
    cmake --build build
}

package() {
    DESTDIR="\$pkgdir" cmake --install build
    install -Dm644 "\$srcdir/$srcdir/COPYING" "\$pkgdir/usr/share/licenses/\$pkgname/COPYING"
}
EOF
}

mkdir -p "$out/penelope" "$out/penelope-git"

cat > "$out/penelope/PKGBUILD" <<EOF
# Maintainer: Clinton <clintonthegeek@github>
# Generated by packaging/generate-pkgbuild.sh for Penelope $version.
# Edit that script, not this file.
#
# Builds the v$version tag. pkgver is the version CMake defines, so the
# package, the About dialog and --version always agree.

pkgname=penelope
pkgver=$version
pkgrel=1
pkgdesc="$pkgdesc"
arch=('x86_64' 'aarch64')
url="$url"
license=('GPL-3.0-only')

depends=(
$deps
)
makedepends=(
$makedeps
)

source=("penelope::git+$repo_url#tag=v$version")
sha256sums=('SKIP')
EOF
build_and_package penelope >> "$out/penelope/PKGBUILD"

cat > "$out/penelope-git/PKGBUILD" <<EOF
# Maintainer: Clinton <clintonthegeek@github>
# Generated by packaging/generate-pkgbuild.sh.
# Edit that script, not this file.
#
# Tracks the default branch. pkgver() derives the version from git describe;
# pkgver below is only the starting value makepkg needs before it runs.

pkgname=penelope-git
pkgver=$version
pkgrel=1
pkgdesc="$pkgdesc (VCS package)"
arch=('x86_64' 'aarch64')
url="$url"
license=('GPL-3.0-only')
provides=('penelope')
conflicts=('penelope')

depends=(
$deps
)
makedepends=(
$makedeps
)

source=("penelope-git::git+$repo_url#branch=main")
sha256sums=('SKIP')

pkgver() {
    cd penelope-git
    local desc
    desc=\$(git describe --long --tags --abbrev=7 2>/dev/null) || desc=""
    if [[ -n "\$desc" ]]; then
        printf '%s' "\$desc" | sed 's/^v//;s/-/.r/;s/-/./'
    else
        printf 'r%s.g%s' "\$(git rev-list --count HEAD)" "\$(git rev-parse --short=7 HEAD)"
    fi
}
EOF
build_and_package penelope-git >> "$out/penelope-git/PKGBUILD"

if command -v makepkg > /dev/null; then
    for dir in penelope penelope-git; do
        ( cd "$out/$dir" && makepkg --printsrcinfo > .SRCINFO )
    done
fi

echo "Generated PKGBUILDs in $out:"
echo "  $out/penelope/PKGBUILD"
echo "  $out/penelope-git/PKGBUILD"
